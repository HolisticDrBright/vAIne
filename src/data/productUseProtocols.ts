function periodsFromTiming(timing: string | null | undefined, fallback: readonly RoutinePeriod[]): readonly RoutinePeriod[] {
  if (!timing) return fallback;
  const hasAm = /\bAM\b|morning|daily body care/i.test(timing);
  const hasPm = /\bPM\b|night|weekly|event/i.test(timing);
  if (hasAm && hasPm) return AM_PM;
  if (hasAm) return AM;
  if (hasPm) return PM;
  return fallback;
}

/**
 * Returns a verified manufacturer protocol when available. Otherwise it
 * exposes the workbook timing note as catalog research and says plainly that
 * the current label still needs verification; it never invents directions.
 */
export function getProductUseProtocol(product: ProtocolProduct): ProductUseProtocol {
  const verified = verifiedProtocols[product.id] ?? verifiedProtocols[protocolAliases[product.id]];
  if (verified) return verified;

  const defaults = product.routineSlot ? slotDefaults[product.routineSlot] : {
    intendedUse: product.category ? `Listed as ${product.category}.` : 'Listed for reference outside the personalized face routine.',
    routineOrder: 'Not placed in the personalized daily face routine.',
    periods: AM_PM,
  };
  const timing = product.whenToUse?.trim() || 'Follow the current package directions.';
  return {
    ...defaults,
    cadence: timing,
    application: 'Exact current manufacturer application directions have not yet been verified in vAIne; check the package before use.',
    periods: periodsFromTiming(product.whenToUse, defaults.periods),
    sourceKind: 'catalog_research',
    sourceLabel: 'Catalog research note — label verification required',
    sourceUrl: null,
    reviewedAtIso: REVIEWED_AT,
    safetyAdaptation: product.routineSlot === 'weekly' ? 'Use on a separate evening from retinoids and other exfoliating acids.' : null,
  };
}

export function protocolSupportsPeriod(product: ProtocolProduct, period: RoutinePeriod): boolean {
  return getProductUseProtocol(product).periods.includes(period);
}

